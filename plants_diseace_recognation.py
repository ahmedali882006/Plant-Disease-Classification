# PHASE 7, 8 & 9: MULTI-MODEL BENCHMARKING & COMPARISON PIPELINE
# ==============================================================================
import tensorflow as tf
from tensorflow.keras import layers, models
from tensorflow.keras.applications import MobileNetV2, EfficientNetB0, EfficientNetB2
from tensorflow.keras.callbacks import EarlyStopping
import numpy as np

# Dictionary containing the architectures we want to test and compare
architectures = {
    "MobileNetV2": MobileNetV2(input_shape=(260, 260, 3), include_top=False, weights='imagenet'),
    "EfficientNetB0": EfficientNetB0(input_shape=(260, 260, 3), include_top=False, weights='imagenet'),
    "EfficientNetB2": EfficientNetB2(input_shape=(260, 260, 3), include_top=False, weights='imagenet')
}

model_results = {}
trained_models = {}

# Loop through each architecture to build, compile, and train for comparison
for model_name, base_model in architectures.items.items() if hasattr(architectures.items(), 'items') else architectures.items():
    print(f"\n==============================================")
    print(f"Training and Evaluating Architecture: {model_name}")
    print(f"==============================================")

    # Freeze the base backbone model
    base_model.trainable = False

    inputs = layers.Input(shape=(260, 260, 3), name=f"{model_name}_input")

    # Apply specific preprocessing if needed, or standard efficientnet scaling
    if "EfficientNet" in model_name:
        x = tf.keras.applications.efficientnet.preprocess_input(inputs)
    else:
        x = tf.keras.applications.mobilenet_v2.preprocess_input(inputs)

    x = base_model(x, training=False)
    x = layers.GlobalAveragePooling2D(name=f"{model_name}_gap")(x)
    x = layers.BatchNormalization(name=f"{model_name}_bn")(x)
    x = layers.Dropout(0.4, name=f"{model_name}_dropout")(x)
    x = layers.Dense(256, activation='swish', name=f"{model_name}_dense")(x)
    outputs = layers.Dense(num_classes, activation='softmax', name=f"{model_name}_output")(x)

    model = models.Model(inputs, outputs, name=model_name)

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    # Quick early stopping to benchmark efficiently within 3 epochs
    callbacks = [
        EarlyStopping(monitor='val_accuracy', patience=1, restore_best_weights=True, verbose=1)
    ]

    history = model.fit(
        train_ds,
        validation_data=val_ds,
        epochs=3,
        callbacks=callbacks,
        verbose=1
    )

    # Record best validation accuracy achieved
    best_val_acc = max(history.history['val_accuracy'])
    model_results[model_name] = best_val_acc
    trained_models[model_name] = model

# ==============================================================================
